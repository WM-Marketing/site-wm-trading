let currentLang = localStorage.getItem('wm-lang') || 'pt';

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('wm-lang', lang);
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';

  // Update textContent elements
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.dataset.i18n;
    var text = translations[lang][key];
    if (text !== undefined) el.textContent = text;
  });

  // Update innerHTML elements
  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    var key = el.dataset.i18nHtml;
    var html = translations[lang][key];
    if (html !== undefined) el.innerHTML = html;
  });

  // Update flag button
  var flag = document.getElementById('lang-flag');
  var code = document.getElementById('lang-code');
  if (flag) flag.textContent = lang === 'pt' ? '🇧🇷' : '🇺🇸';
  if (code) code.textContent = lang === 'pt' ? 'PT' : 'EN';
}

document.addEventListener('DOMContentLoaded', function() {
  var toggle = document.getElementById('lang-toggle');
  if (toggle) {
    toggle.addEventListener('click', function() {
      setLang(currentLang === 'pt' ? 'en' : 'pt');
    });
  }

  // Apply saved/default language on load
  setLang(currentLang);
});
